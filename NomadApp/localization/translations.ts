export function detectLanguage(languageTag?: string | null, languageCode?: string | null): Language {
  const normalized = (languageCode ?? languageTag ?? '').toLowerCase();
  return normalized.startsWith('mn') ? 'mn' : 'en';
}

export function getTranslation(language: Language, key: string): string | undefined {
  const segments = key.split('.');
  let current: string | TranslationTree | undefined = translations[language];

  for (const segment of segments) {
    if (!current || typeof current === 'string') return undefined;
    current = current[segment];
  }

  return typeof current === 'string' ? current : undefined;
}

export function interpolate(
  template: string,
  params?: Record<string, string | number>
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, token: string) => {
    const value = params?.[token];
    return value == null ? match : String(value);
  });
}
